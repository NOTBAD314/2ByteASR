def expand(question: str) -> str:
    """The question plus the entry words its colloquial wording stands for."""
    text = str(question or '')
    extra = [words for said, words in SYNONYMS.items() if said in text]
    return f'{text} {" ".join(extra)}' if extra else text


def _t(stage, key, title, keywords, *lines, pages=()):
    hints = ' '.join(lines[:2])
    return LoreEntry(f'trouble:{stage}:{key}', f'{STAGES[stage]} · {title}', tuple(keywords), '\n'.join(lines),
                     hints, tuple(pages))


