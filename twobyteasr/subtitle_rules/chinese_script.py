"""简体 / 繁體 for recognized Chinese subtitles (2026-10-19, ADR 0132).

The home page "字幕语言" offers 简体中文 and 繁体中文. Both run the same
Chinese recognition (models, glossary, timeline); 繁体中文 only converts the
delivered subtitles once, locally, right before the project is written
(``convert_delivered_cues``). The project, the workbench and every export then
hold the Traditional text; the recognition evidence stays as heard.

Conversion: the longest OpenCC ``s2tw`` phrase at each position, otherwise the
character (data in ``locales/zh-Hant-subtitles.json``, generated by
``scripts/make_zh_hant_subtitles.py``). Character forms only (裡, 為, 著, 頭髮,
之後); vocabulary is kept (视频 → 視頻, not 影片). Every character becomes
exactly one character, so text indexes, word timings and the punctuation
index map stay valid.

``fold_map`` gives every 简/繁 pair of the table one key, so a Traditional cue
still matches its Simplified word evidence (``cue_word_alignment``).

Afternoon of 2026-10-19: ``to_simplified`` reads the reverse table
(``locales/zh-Hans-subtitles.json``, OpenCC ``tw2s``, also length-preserving)
for the workbench command that converts a whole project either way;
``project_script`` reads ``generation_metadata.language.script`` and
``for_project`` converts newly produced text of a 繁體 project.
"""
from __future__ import annotations

import json
from pathlib import Path

SIMPLIFIED = "zh-Hans"
TRADITIONAL = "zh-Hant"
SCRIPTS = (SIMPLIFIED, TRADITIONAL)
DEFAULT_SCRIPT = SIMPLIFIED
TABLE_PATH = Path(__file__).resolve().parents[1] / "locales" / "zh-Hant-subtitles.json"
REVERSE_TABLE_PATH = TABLE_PATH.with_name("zh-Hans-subtitles.json")

_TABLE: tuple[dict, dict, dict] | None = None
_REVERSE: tuple[dict, dict, dict] | None = None
_FOLD: dict[str, str] | None = None


def _load(path: Path) -> tuple[dict, dict, dict]:
    """(characters, phrases, longest phrase per first character); empty when the data is missing."""
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        chars = {str(k): str(v) for k, v in dict(payload["chars"]).items() if len(k) == len(v) == 1}
        phrases: dict[str, str | None] = {str(k): str(v) for k, v in dict(payload["phrases"]).items()
                                          if len(k) == len(v) > 1}
        for key in payload.get("same") or ():
            # Converted character by character, but still matched as a whole.
            phrases.setdefault(str(key), None)
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        chars, phrases = {}, {}
    longest: dict[str, int] = {}
    for key in phrases:
        longest[key[0]] = max(longest.get(key[0], 0), len(key))
    return chars, phrases, longest


def _table() -> tuple[dict, dict, dict]:
    """简 → 繁 (``s2tw``)."""
    global _TABLE
    if _TABLE is None:
        _TABLE = _load(TABLE_PATH)
    return _TABLE


def _reverse_table() -> tuple[dict, dict, dict]:
    """繁 → 简 (``tw2s``), loaded only when something is converted back."""
    global _REVERSE
    if _REVERSE is None:
        _REVERSE = _load(REVERSE_TABLE_PATH)
    return _REVERSE


def available(script: str = TRADITIONAL) -> bool:
    """Whether text can be converted into ``script``."""
    return bool((_reverse_table() if script == SIMPLIFIED else _table())[0])


def normalize_script(value) -> str:
    return value if value in SCRIPTS else DEFAULT_SCRIPT


def to_traditional(text: str) -> str:
    """繁體 of ``text``; the same length, non-Chinese characters unchanged."""
    return _convert(text, _table())


def to_simplified(text: str) -> str:
    """简体 of ``text``; the same length, non-Chinese characters unchanged."""
    return _convert(text, _reverse_table())


def convert_text(text: str, script: str) -> str:
    """``text`` written in ``script`` (zh-Hant or zh-Hans)."""
    return to_traditional(text) if script == TRADITIONAL else to_simplified(text)


def _convert(text: str, table) -> str:
    chars, phrases, longest = table
    if not text or not chars:
        return text
    out = []
    index, size = 0, len(text)
    while index < size:
        matched = 0
        for length in range(min(longest.get(text[index], 0), size - index), 1, -1):
            piece = text[index:index + length]
            if piece in phrases:
                value = phrases[piece]
                out.append(value if value is not None else "".join(chars.get(ch, ch) for ch in piece))
                matched = length
                break
        if matched:
            index += matched
        else:
            out.append(chars.get(text[index], text[index]))
            index += 1
    return "".join(out)


def fold_map() -> dict[str, str]:
    """Character → script-insensitive key: each 简/繁 group of the table shares one character."""
    global _FOLD
    if _FOLD is None:
        chars, phrases, _longest = _table()
        parent: dict[str, str] = {}

        def find(ch):
            root = ch
            while parent.get(root, root) != root:
                root = parent[root]
            while parent.get(ch, ch) != root:
                parent[ch], ch = root, parent[ch]
            return root

        def union(a, b):
            a, b = find(a), find(b)
            if a != b:
                parent[max(a, b)] = min(a, b)

        for simplified, traditional in chars.items():
            union(simplified, traditional)
        for key, value in phrases.items():
            for simplified, traditional in zip(key, value or ()):
                if simplified != traditional:
                    union(simplified, traditional)
        _FOLD = {ch: find(ch) for ch in list(parent)}
    return _FOLD


def fold(text: str) -> str:
    """``text`` with each 简/繁 character replaced by its group key: same length, same indexes."""
    if not text:
        return text
    table = fold_map()
    return "".join(table.get(ch, ch) for ch in text)


def project_script(project) -> str:
    """zh-Hant when the project records 繁體 subtitles (delivered or converted), else zh-Hans."""
    metadata = getattr(project, "generation_metadata", None)
    language = metadata.get("language") if isinstance(metadata, dict) else None
    return normalize_script(language.get("script") if isinstance(language, dict) else None)


def glossary_script(project) -> str | None:
    """``script`` for a project's glossary checks: zh-Hant for a 繁體 project, else None (exact, as before)."""
    return TRADITIONAL if project_script(project) == TRADITIONAL else None


def for_project(text, project):
    """Newly produced Chinese text for ``project``: 繁體 when its subtitles are 繁體, else unchanged."""
    if not isinstance(text, str) or not text or project_script(project) != TRADITIONAL:
        return text
    return to_traditional(text)


def task_script(runtime_context) -> str:
    """The script of this task's Chinese subtitles: 繁體 only when chosen, Chinese and the table is there."""
    if normalize_script(getattr(runtime_context, "chinese_script", DEFAULT_SCRIPT)) != TRADITIONAL:
        return SIMPLIFIED
    language = str(getattr(runtime_context, "task_language", "") or "zh")
    return TRADITIONAL if language == "zh" and available() else SIMPLIFIED


def convert_delivered_cues(cues, runtime_context, legacy=None) -> list[dict]:
    """繁体中文 chosen for a Chinese task: convert the final cue text once, before the project exists."""
    if normalize_script(getattr(runtime_context, "chinese_script", DEFAULT_SCRIPT)) != TRADITIONAL:
        return []
    record = getattr(legacy, "record_run_event", None)
    language = str(getattr(runtime_context, "task_language", "") or "zh")
    if language != "zh" or not available():
        reason = "not_chinese" if language != "zh" else "table_missing"
        if callable(record):
            record("chinese_script_skipped", reason=reason, language=language)
        print("   [繁体] 识别语言不是中文，字幕保持原文。" if language != "zh"
              else "   [繁体] 缺少简繁转换表，字幕保持简体。")
        return []
    changed = []
    for cue in cues:
        text = getattr(cue, "text", None)
        if not isinstance(text, str):
            continue
        converted = to_traditional(text)
        if converted != text:
            cue.text = converted
            changed.append({"cue_id": getattr(cue, "cue_id", None), "before": text, "after": converted})
    if callable(record):
        record("chinese_script_converted", script=TRADITIONAL, cues=len(changed), samples=changed[:10])
    print(f"   [繁体] 已在本机把 {len(changed)} 条字幕转换为繁体中文（只换字形，不改用词）。")
    return changed
